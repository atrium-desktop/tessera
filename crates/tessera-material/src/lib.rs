/// Per-group backdrop statistics.
#[derive(Debug, Default, Clone, Copy, PartialEq)]
pub struct BackdropStats {
    pub mean_luminance: f32,
    pub high_freq_energy: f32,
}

const _: () = assert!(
    std::mem::size_of::<BackdropStats>()
        == std::mem::size_of::<sys::tessera_material_backdrop_stat>()
);
const _: () = assert!(
    std::mem::align_of::<BackdropStats>()
        == std::mem::align_of::<sys::tessera_material_backdrop_stat>()
);

/// Reusable analytic liquid-glass compositor.
pub struct LiquidGlassFilter {
    raw: *mut sys::tessera_material_liquid_glass_filter,
}

impl LiquidGlassFilter {
    pub fn new(device: &optics_gfx::Device) -> Result<Self, Error> {
        let mut raw = std::ptr::null_mut();
        check(unsafe {
            sys::tessera_material_liquid_glass_filter_create(device.as_raw(), &mut raw)
        })?;
        Ok(Self { raw })
    }

    /// Pre-warm compute pipelines to eliminate first-frame JIT hitches (ADR-0141, ADR-0142).
    pub fn warmup(&mut self, opts: Option<&WarmupOpts>) -> Result<(), Error> {
        let raw_opts = opts.map(|o| sys::tessera_material_liquid_glass_warmup_opts {
            format: o.format.as_raw(),
            stats: o.stats,
        });
        check(unsafe {
            sys::tessera_material_liquid_glass_filter_warmup(
                self.raw,
                raw_opts.as_ref().map_or(std::ptr::null(), |r| r),
            )
        })
    }

    pub fn apply<'filter>(
        &'filter mut self,
        frame: &optics_gfx::Frame<'_>,
        input: &optics_gfx::Image,
        blurred: &optics_gfx::BlurredImage<'_>,
        groups: &[LiquidGlassGroup],
        params: LiquidGlassParams,
    ) -> Result<LiquidGlassImage<'filter>, Error> {
        let raw_groups: Vec<RawGroup> = groups.iter().map(LiquidGlassGroup::as_raw).collect();
        // RawGroup is a plain-Data group descriptor plus its owned shapes
        // box; copy the descriptor (the borrowed shapes pointer stays valid
        // because the RawGroup vector outlives the call below).
        let group_ptrs: Vec<sys::tessera_material_liquid_glass_group> = raw_groups
            .iter()
            .map(|g| unsafe { std::ptr::read(&g.group) })
            .collect();
        let desc = sys::tessera_material_liquid_glass_desc {
            type_: sys::tessera_material_struct_type::TESSERA_MATERIAL_TYPE_LIQUID_GLASS_DESC,
            input: input.as_raw(),
            blurred_input: blurred.as_raw(),
            groups: if group_ptrs.is_empty() {
                std::ptr::null()
            } else {
                group_ptrs.as_ptr()
            },
            group_count: u32::try_from(group_ptrs.len()).unwrap_or(u32::MAX),
            refraction: params.refraction,
            chromatic_aberration: params.chromatic_aberration,
            saturation: params.saturation,
            brightness: params.brightness,
            edge_width: params.edge_width,
            rim_light: params.rim_light,
            light_direction: sys::optics_gfx_point {
                x: params.light_direction.0,
                y: params.light_direction.1,
            },
            opacity: params.opacity,
            size_reference: params.size_reference,
            size_scale_min: params.size_scale_min,
            tint_strength: params.tint_strength,
            frost_strength: params.frost_strength,
            curvature: params.curvature,
            contact_ao: params.contact_ao,
            ambient_fresnel: params.ambient_fresnel,
            ..Default::default()
        };
        let mut out = sys::tessera_material_output::default();
        let opts = sys::tessera_material_liquid_glass_filter_apply_opts {
            frame: frame.as_raw(),
            desc: &desc,
            out: &mut out,
        };
        check(unsafe { sys::tessera_material_liquid_glass_filter_apply(self.raw, &opts) })?;
        Ok(LiquidGlassImage {
            raw: out.image,
            origin_x: out.origin_x,
            origin_y: out.origin_y,
            width: out.width,
            height: out.height,
            _filter: PhantomData,
        })
    }

    pub fn stats(
        &mut self,
        frame: &optics_gfx::Frame<'_>,
        out: &mut [BackdropStats],
    ) -> Result<usize, Error> {
        let mut count = 0u32;
        let opts = sys::tessera_material_liquid_glass_filter_stats_opts {
            frame: frame.as_raw(),
            out: out
                .as_mut_ptr()
                .cast::<sys::tessera_material_backdrop_stat>(),
            max_groups: u32::try_from(out.len()).unwrap_or(u32::MAX),
            out_count: &mut count,
        };
        check(unsafe { sys::tessera_material_liquid_glass_filter_stats(self.raw, &opts) })?;
        Ok(count as usize)
    }
}

impl Drop for LiquidGlassFilter {
    fn drop(&mut self) {
        unsafe { sys::tessera_material_liquid_glass_filter_release(self.raw) };
    }
}

/// Borrowed output of a [`LiquidGlassFilter`] application.
///
/// The image is a *slab*: it is sized to the union of the bodies' footprints, not
/// to the input capture, and [`origin`](Self::origin) says where it belongs in
/// capture pixels. [`draw`](Self::draw) honours that automatically; drawing the
/// raw image at the capture origin would smear every body to the wrong place.
pub struct LiquidGlassImage<'filter> {
    raw: *mut sys::optics_gfx_image,
    origin_x: f32,
    origin_y: f32,
    width: u32,
    height: u32,
    _filter: PhantomData<&'filter mut LiquidGlassFilter>,
}

fn draw_image_rect(
    canvas: &optics_gfx::CanvasCommands<'_>,
    image: *mut optics_gfx_sys::optics_gfx_image,
    dst: sys::optics_gfx_rect,
) {
    let geom = optics_gfx_sys::optics_gfx_geometry {
        kind: optics_gfx_sys::optics_gfx_geom_kind::OPTICS_GFX_GEOM_RECT,
        _pad: [0; 3],
        stroke: Default::default(),
        __bindgen_anon_1: optics_gfx_sys::optics_gfx_geometry__bindgen_ty_1 {
            rect: optics_gfx_sys::optics_gfx_geom_rect_data { rect: dst },
        },
    };
    let brush = optics_gfx_sys::optics_gfx_brush {
        kind: optics_gfx_sys::optics_gfx_brush_kind::OPTICS_GFX_BRUSH_IMAGE_PATTERN,
        blend: optics_gfx_sys::optics_gfx_blend_mode::OPTICS_GFX_BLEND_SRC_OVER,
        opacity: 1.0,
        __bindgen_anon_1: optics_gfx_sys::optics_gfx_brush__bindgen_ty_1 {
            image: optics_gfx_sys::optics_gfx_brush_image_data {
                image,
                sampler: std::ptr::null_mut(),
                src_rect: optics_gfx_sys::optics_gfx_rect {
                    x: 0.0,
                    y: 0.0,
                    w: 0.0,
                    h: 0.0,
                },
                opaque_only: false,
                tint: 0xFFFFFFFF,
                clip_rect: optics_gfx_sys::optics_gfx_rect {
                    x: 0.0,
                    y: 0.0,
                    w: 0.0,
                    h: 0.0,
                },
                clip_radii: optics_gfx::CornerRadii::ZERO.to_raw(),
                clip_curvature: 0.0,
            },
        },
    };
    let opts = optics_gfx_sys::optics_gfx_canvas_draw_geometry_opts {
        geom: &geom,
        brush: &brush,
    };
    unsafe { optics_gfx_sys::optics_gfx_canvas_draw_geometry(canvas.as_raw(), &opts) };
}

impl LiquidGlassImage<'_> {
    /// Where the slab belongs in capture pixels.
    pub fn origin(&self) -> (f32, f32) {
        (self.origin_x, self.origin_y)
    }

    /// The slab's extent in capture pixels (its image's own extent).
    pub fn extent(&self) -> (u32, u32) {
        (self.width, self.height)
    }

    /// Draw the material at its placement. This is the only correct way to
    /// composite it: the slab's origin is part of the output contract.
    pub fn draw(&self, canvas: &optics_gfx::CanvasCommands<'_>) {
        let destination = sys::optics_gfx_rect {
            x: self.origin_x,
            y: self.origin_y,
            w: self.width as f32,
            h: self.height as f32,
        };
        draw_image_rect(canvas, self.raw, destination);
    }
}

