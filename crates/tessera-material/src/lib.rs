/// One rounded-rectangle volume in backdrop-capture pixel coordinates.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct LiquidGlassShape {
    pub x: f32,
    pub y: f32,
    pub width: f32,
    pub height: f32,
    pub corner_radius: f32,
}

/// One soft optical emphasis field inside an existing glass body.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct LiquidGlassFocus {
    pub shape: LiquidGlassShape,
    pub strength: f32,
}

/// One independently composited glass body.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct LiquidGlassGroup {
    pub primary: LiquidGlassShape,
    pub merged: Option<LiquidGlassShape>,
    pub blend_radius: f32,
    pub opacity: f32,
    pub shadow_alpha: f32,
    pub shadow_blur: f32,
    pub shadow_offset_y: f32,
    pub tint_color: [u8; 3],
    pub focus: Option<LiquidGlassFocus>,
    pub frost_strength: Option<f32>,
    pub tint_strength: Option<f32>,
    pub saturation: Option<f32>,
    pub curvature: Option<f32>,
    pub contact_ao: Option<f32>,
    pub ambient_fresnel: Option<f32>,
}

impl LiquidGlassGroup {
    /// Build the C-side group. The returned [`RawGroup`] owns the
    /// heap-allocated borrowed-shape array; keep it alive for the
    /// duration of the C call that reads the group (`apply` does).
    pub fn as_raw(&self) -> RawGroup {
        let raw_shape = |shape: LiquidGlassShape| sys::tessera_material_liquid_glass_shape {
            bounds: sys::optics_gfx_rect {
                x: shape.x,
                y: shape.y,
                w: shape.width,
                h: shape.height,
            },
            corner_radius: shape.corner_radius,
        };
        let sentinel = |value: Option<f32>| value.unwrap_or(-1.0);
        let mut shapes = Box::new([raw_shape(self.primary), raw_shape(self.primary)]);
        let shape_count = if let Some(merged) = self.merged {
            shapes[1] = raw_shape(merged);
            2
        } else {
            1
        };
        let group = sys::tessera_material_liquid_glass_group {
            shapes: shapes.as_ptr(),
            shape_count,
            blend_radius: self.blend_radius,
            opacity: self.opacity,
            shadow_alpha: self.shadow_alpha,
            shadow_blur: self.shadow_blur,
            shadow_offset_y: self.shadow_offset_y,
            tint_color: (u32::from(self.tint_color[0]) << 16)
                | (u32::from(self.tint_color[1]) << 8)
                | u32::from(self.tint_color[2]),
            focus: self
                .focus
                .map(|focus| raw_shape(focus.shape))
                .unwrap_or_else(|| raw_shape(self.primary)),
            focus_strength: self.focus.map_or(0.0, |focus| focus.strength),
            frost_strength: sentinel(self.frost_strength),
            tint_strength: sentinel(self.tint_strength),
            saturation: sentinel(self.saturation),
            curvature: sentinel(self.curvature),
            contact_ao: sentinel(self.contact_ao),
            ambient_fresnel: sentinel(self.ambient_fresnel),
        };
        RawGroup {
            group,
            _shapes: Box::into_raw(shapes),
        }
    }
}

/// C-side view of a [`LiquidGlassGroup`] plus the owned shape storage the
/// group borrows. Dropping this frees the array; the raw group pointer
/// inside is only valid while this value is alive.
pub struct RawGroup {
    pub group: sys::tessera_material_liquid_glass_group,
    // Owned storage for the borrowed `shapes` array (2 slots: primary
    // + merged/focus); released on drop.
    _shapes: *mut [sys::tessera_material_liquid_glass_shape; 2],
}

impl Drop for RawGroup {
    fn drop(&mut self) {
        // SAFETY: allocated by Box::into_raw in as_raw; freed exactly once.
        if !self._shapes.is_null() {
            unsafe { drop(Box::from_raw(self._shapes)) };
        }
    }
}

impl std::ops::Deref for RawGroup {
    type Target = sys::tessera_material_liquid_glass_group;
    fn deref(&self) -> &Self::Target {
        &self.group
    }
}

