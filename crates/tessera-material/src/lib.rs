//! Tessera's backdrop materials (ADR-0262): frosted and liquid glass on the
//! Optics gfx public effect runtime.
//!
//! Optics carried these as `optics-material` until its ADR-0174 made it a
//! pure graphics and UI core. Tessera owns the material identity now: the C
//! filters and their compute shaders live in this crate and are compiled into
//! it, so nothing here links a separate material library.
//!
//! Materials:
//! - [`LiquidGlassFilter`]: analytic convex-lens liquid glass compositor.
//! - [`FrostedFilter`]: classic non-distorting frosted glass compositor.

#![deny(rust_2018_idioms)]

use std::marker::PhantomData;

/// Raw FFI to the vendored C filters, generated by bindgen from
/// `csrc/include/tessera/material.h`.
#[allow(
    non_camel_case_types,
    non_snake_case,
    non_upper_case_globals,
    dead_code,
    unsafe_op_in_unsafe_fn,
    clippy::all,
    clippy::pedantic
)]
pub mod sys {
    pub use optics_gfx_sys::*;
    include!(concat!(env!("OUT_DIR"), "/bindings.rs"));
}

/// A material failure, surfaced through gfx's result codes: every fallible
/// material call returns `optics_gfx_result`, so the error type is gfx's own.
pub use optics_gfx::Error;

/// Map a raw result to `Ok(())` on `OPTICS_GFX_OK`, else `Err`.
fn check(rc: sys::optics_gfx_result) -> Result<(), Error> {
    if rc == sys::optics_gfx_result::OPTICS_GFX_OK {
        Ok(())
    } else {
        Err(Error(rc))
    }
}

/// Material filter compute pipeline pre-warming configuration (ADR-0141, ADR-0142).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct WarmupOpts {
    /// Target image format (default: RGBA8 UNORM).
    pub format: optics_gfx::Format,
    /// Pre-warm stats reduction pipeline when supported.
    pub stats: bool,
}

impl Default for WarmupOpts {
    fn default() -> Self {
        Self {
            format: optics_gfx::Format::Rgba8Unorm,
            stats: true,
        }
    }
}

