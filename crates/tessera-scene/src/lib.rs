//! Tessera's 3D scene runtime (ADR-0262): glTF 2.0 / VRM loading, a scene
//! hierarchy with animation, and a depth-tested mesh renderer.
//!
//! Optics carried this as `optics-scene` plus the gfx scene core until its
//! ADR-0174 made Optics a pure 2D graphics and UI stack. The C runtime and
//! its shaders now live in this crate, compiled in statically, and render
//! through the Optics gfx public RHI: draws record into an
//! [`optics_gfx::RenderPass`].
//!
//! Embedded textures are decoded by the caller
//! ([`Scene::from_glb_with_materials_and_decoder`]); this crate links no
//! image codec.

#![deny(rust_2018_idioms)]

